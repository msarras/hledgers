//! Transactions changed or made by rules: auto posting rules
//! (Hledger.Data.TransactionModifier), which add postings to the
//! transactions they match, and periodic transaction rules
//! (Hledger.Data.PeriodicTransaction), which generate transactions when
//! forecasting.

use crate::amount::{Amount, CommodityStyles};
use crate::dates::{DateSpan, Day, split_span_to_date_spans};
use crate::model::{
    GENERATED_POSTING_TAG, GENERATED_TRANSACTION_TAG, Journal, MODIFIED_TRANSACTION_TAG,
    PeriodicTransaction, Posting, PostingRef, TmPostingRule, Transaction, TransactionModifier,
    comment_add_tag, comment_join,
};
use crate::query::{Query, parse_query};

/// Apply the journal's auto posting rules to its transactions, the
/// generated postings styled with the journal's commodity styles
/// (journalModifyTransactions).
pub fn journal_modify_transactions(
    verbose_tags: bool,
    today: Day,
    mut j: Journal,
) -> Result<Journal, String> {
    let styles = j.commodity_styles();
    let txns = std::mem::take(&mut j.txns);
    j.txns = modify_transactions(&j, &j.txn_modifiers, &styles, today, verbose_tags, txns)?;
    Ok(j)
}

/// Apply auto posting rules to transactions (modifyTransactions): each
/// rule in turn, so a later rule sees the postings an earlier one added,
/// and its postings follow the matched posting, before any added by
/// earlier rules. Generated postings get these styles, and the journal's
/// tags for their accounts; a transaction that gets postings is tagged as
/// modified (visibly too, with `verbose_tags`). Relative dates in the
/// rules' queries are relative to `today`.
pub fn modify_transactions(
    j: &Journal,
    modifiers: &[TransactionModifier],
    styles: &CommodityStyles,
    today: Day,
    verbose_tags: bool,
    mut txns: Vec<Transaction>,
) -> Result<Vec<Transaction>, String> {
    let rules = modifiers
        .iter()
        .map(|tm| Ok((parse_query(today, &tm.query)?.0.simplify(), tm)))
        .collect::<Result<Vec<_>, String>>()?;
    for t in &mut txns {
        let mut modified = false;
        for (q, tm) in &rules {
            let mut postings = Vec::with_capacity(t.postings.len());
            for p in &t.postings {
                postings.push(p.clone());
                if !q.matches_posting_extra(&|a| j.account_type(a), PostingRef::new(t, p)) {
                    continue;
                }
                for rule in &tm.rules {
                    let mut new = tm_posting_rule_posting(verbose_tags, q, &tm.query, rule, p);
                    new.style_amounts(styles);
                    new.add_tags(j.inherited_account_tags(&new.account));
                    postings.push(new);
                    modified = true;
                }
            }
            t.postings = postings;
        }
        if modified {
            t.add_hidden_and_maybe_visible_tag(
                verbose_tags,
                (MODIFIED_TRANSACTION_TAG.into(), String::new()),
            );
        }
    }
    Ok(txns)
}

/// The posting an auto posting rule's posting makes from a matched posting
/// (tmPostingRuleToFunction): with the matched posting's dates unless it
/// has its own (shown in its comment), `%account` in its account replaced
/// by the matched account, and as its amount its own, or if it is a
/// multiplier, the matched amounts the query's amt: and cur: terms select,
/// multiplied (in the multiplier's commodity, if it has one). It is tagged
/// as generated by the rule's query, visibly too with `verbose_tags`.
fn tm_posting_rule_posting(
    verbose_tags: bool,
    q: &Query,
    query_text: &str,
    rule: &TmPostingRule,
    p: &Posting,
) -> Posting {
    let pr = &rule.posting;
    let qry = format!("= {query_text}");
    let account = if pr.account.contains("%account") {
        pr.account.replace("%account", &p.account).into()
    } else {
        pr.account.clone()
    };
    let amount = match (pr.amount.amounts_raw(), rule.is_multiplier) {
        ([m], true) => {
            let symq = q.clone().filter(|q| q.is_cur() || q.is_amt());
            let matched = p.amount.clone().filter(|a| symq.matches_amount(a));
            let multiplied = matched.multiply(&m.quantity);
            if m.commodity.is_empty() {
                multiplied
            } else {
                multiplied.map(|a| Amount {
                    commodity: m.commodity.clone(),
                    style: m.style.clone(),
                    cost: m.cost.clone(),
                    ..a.clone()
                })
            }
        }
        _ => pr.amount.clone(),
    };
    let tag = (GENERATED_POSTING_TAG[1..].to_string(), qry.clone());
    let mut tags = Vec::new();
    if verbose_tags {
        tags.push(tag.clone());
    }
    tags.push((GENERATED_POSTING_TAG.to_string(), qry));
    tags.extend(pr.tags.iter().cloned());
    let mut new = Posting {
        date: pr.date.or(p.date),
        date2: pr.date2.or(p.date2),
        account,
        amount,
        comment: if verbose_tags {
            comment_add_tag(&pr.comment, &tag)
        } else {
            pr.comment.clone()
        },
        tags,
        ..pr.clone()
    };
    render_posting_comment_dates(&mut new);
    new
}

/// A posting's own dates written at the start of its comment, as `[DATE]`
/// or `[DATE=DATE2]` (renderPostingCommentDates).
fn render_posting_comment_dates(p: &mut Posting) {
    let mut dates = p.date.map(|d| d.to_string()).unwrap_or_default();
    if let Some(d2) = p.date2 {
        dates.push_str(&format!("={d2}"));
    }
    if !dates.is_empty() {
        p.comment = comment_join(&format!("[{dates}]"), &p.comment);
    }
}

/// The dates in a span on which a periodic transaction rule generates
/// transactions: the starts of its periods, within the rule's own dates,
/// which default to the span's; without a start date, periods are aligned
/// to the interval (periodicTransactionDates).
pub fn periodic_transaction_dates(
    pt: &PeriodicTransaction,
    requested: DateSpan,
) -> Result<impl Iterator<Item = Day>, String> {
    let span = pt.span.valid_defaults_from(requested);
    Ok(
        split_span_to_date_spans(span.start().is_none(), &pt.interval, span)?
            .filter_map(|s| s.start())
            .filter(move |d| requested.contains(*d)),
    )
}

/// The transactions a periodic transaction rule generates in a span,
/// tagged with its period expression (visibly too, with `verbose_tags`)
/// (runPeriodicTransaction).
pub fn run_periodic_transaction(
    verbose_tags: bool,
    pt: &PeriodicTransaction,
    requested: DateSpan,
) -> Result<Vec<Transaction>, String> {
    let mut t = Transaction {
        pos: pt.pos.clone(),
        status: pt.status,
        code: pt.code.clone(),
        description: pt.description.clone(),
        comment: pt.comment.clone(),
        tags: pt.tags.clone(),
        postings: pt.postings.clone(),
        ..Transaction::default()
    };
    let tag = (
        GENERATED_TRANSACTION_TAG.to_string(),
        format!("~ {}", pt.period_expr),
    );
    t.add_hidden_and_maybe_visible_tag(verbose_tags, tag);
    Ok(periodic_transaction_dates(pt, requested)?
        .map(|date| Transaction { date, ..t.clone() })
        .collect())
}

pub(crate) mod tests {
    use super::*;
    use crate::amount::{MixedAmount, num, usd};
    use crate::model::TransactionModifier;
    use crate::model::render::{PostingLayout, show_transaction};

    fn rule(account: &str, amount: Amount, is_multiplier: bool) -> TmPostingRule {
        TmPostingRule {
            posting: Posting {
                account: account.into(),
                amount: MixedAmount::from_amount(amount),
                ..Posting::default()
            },
            is_multiplier,
        }
    }

    fn d(s: &str) -> crate::decimal::Decimal {
        s.parse().unwrap()
    }

    /// The transactionModifierToFunction doctests: a rule applied to
    /// `ping $1`, shown with verbose tags.
    fn apply(query: &str, rules: Vec<TmPostingRule>) -> String {
        let t = Transaction {
            postings: vec![Posting::new("ping", usd(d("1")))],
            ..Transaction::default()
        };
        let j = Journal {
            txns: vec![t],
            txn_modifiers: vec![TransactionModifier {
                query: query.to_string(),
                rules,
                pos: crate::model::SourcePos::null(),
            }],
            ..Journal::default()
        };
        let mut j = journal_modify_transactions(true, crate::dates::null_date(), j).unwrap();
        let t = &mut j.txns[0];
        t.comment.clear();
        show_transaction(t, PostingLayout::default(), false)
    }

    /// The runPeriodicTransaction doctests: the transactions a rule with
    /// posting `a $1` generates in a span, shown.
    fn ptgen(expr: &str, span: DateSpan) -> String {
        let (interval, pspan) =
            crate::dates::parse_period_expr(crate::dates::null_date(), expr).unwrap();
        let pt = PeriodicTransaction {
            period_expr: expr.to_string(),
            interval,
            span: pspan,
            pos: Transaction::default().pos,
            status: Default::default(),
            code: String::new(),
            description: String::new(),
            comment: String::new(),
            tags: Vec::new(),
            postings: vec![Posting::new("a", usd(d("1")))],
        };
        run_periodic_transaction(true, &pt, span)
            .unwrap()
            .iter()
            .map(|t| show_transaction(t, PostingLayout::default(), false))
            .collect()
    }

    fn flex(y: i64, m: u32, dd: u32) -> Option<crate::dates::EfDay> {
        Some(crate::dates::EfDay {
            day: crate::dates::Day::from_ymd(y, m, dd).unwrap(),
            exact: false,
        })
    }

    #[cfg_attr(test, test)]
    pub(crate) fn periodic_transactions() {
        let gen_dates = |expr: &str, span: DateSpan| -> Vec<String> {
            ptgen(expr, span)
                .split("\n\n")
                .filter(|t| !t.is_empty())
                .map(|t| t[..10].to_string())
                .collect()
        };
        let all = DateSpan::default();
        assert_eq!(
            ptgen("monthly from 2017/1 to 2017/4", all)
                .split("\n\n")
                .next()
                .unwrap(),
            "2017-01-01\n    ; generated-transaction: ~ monthly from 2017/1 to 2017/4\n    a                                             $1.00"
        );
        assert_eq!(
            gen_dates("monthly from 2017/1 to 2017/4", all),
            ["2017-01-01", "2017-02-01", "2017-03-01"]
        );
        assert_eq!(
            gen_dates("monthly from 2017/1 to 2017/5", all),
            ["2017-01-01", "2017-02-01", "2017-03-01", "2017-04-01"]
        );
        assert_eq!(
            gen_dates("every 2nd day of month from 2017/02 to 2017/04", all),
            ["2017-02-02", "2017-03-02"]
        );
        assert_eq!(
            gen_dates("every 30th day of month from 2017/1 to 2017/5", all),
            ["2017-01-30", "2017-02-28", "2017-03-30", "2017-04-30"]
        );
        assert_eq!(
            gen_dates("every 2nd Thursday of month from 2017/1 to 2017/4", all),
            ["2017-01-12", "2017-02-09", "2017-03-09"]
        );
        assert_eq!(
            gen_dates("every nov 29th from 2017 to 2019", all),
            ["2017-11-29", "2018-11-29"]
        );
        assert_eq!(gen_dates("2017/1", all), ["2017-01-01"]);
        assert!(
            gen_dates(
                "daily from 2018/01/03",
                DateSpan(flex(2018, 1, 1), flex(2018, 1, 3))
            )
            .is_empty()
        );
        assert!(
            gen_dates(
                "every 3 months from 2019-05",
                DateSpan(flex(2020, 1, 1), flex(2020, 2, 1))
            )
            .is_empty()
        );
        assert_eq!(
            gen_dates(
                "every 3 months from 2019-05",
                DateSpan(flex(2020, 2, 1), flex(2020, 3, 1))
            ),
            ["2020-02-01"]
        );
        assert_eq!(
            gen_dates(
                "every 3 days from 2018",
                DateSpan(flex(2018, 1, 1), flex(2018, 1, 5))
            ),
            ["2018-01-01", "2018-01-04"]
        );
        assert_eq!(
            gen_dates(
                "every 3 days from 2018",
                DateSpan(flex(2018, 1, 2), flex(2018, 1, 5))
            ),
            ["2018-01-04"]
        );
    }

    #[cfg_attr(test, test)]
    pub(crate) fn auto_postings() {
        assert_eq!(
            apply("", vec![rule("pong", usd(d("2")), false)]),
            "0000-01-01\n    ping                                          $1.00\n    pong                                          $2.00  ; generated-posting: =\n\n"
        );
        assert_eq!(
            apply("miss", vec![rule("pong", usd(d("2")), false)]),
            "0000-01-01\n    ping                                          $1.00\n\n"
        );
        assert_eq!(
            apply("ping", vec![rule("pong", num(d("3")), true)]),
            "0000-01-01\n    ping                                          $1.00\n    pong                                          $3.00  ; generated-posting: = ping\n\n"
        );
    }
}
