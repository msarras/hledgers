/// Run the rewrite command (rewrite): apply the auto posting rule of the
/// query arguments and --add-posting options, then the journal's own rules,
/// with no commodity styles, and print all the transactions as print does,
/// or with --diff, show the changes.
pub fn rewrite(opts: &CliOpts, j: Journal) -> Result<String, String> {
    let raw = &opts.raw;
    let mut modifiers = vec![transaction_modifier_from_opts(opts)?];
    modifiers.extend(j.txn_modifiers.iter().cloned());
    let verbose_tags = raw.bool("verbose-tags");
    let today = opts.spec.today;
    let txns = modify_transactions(
        &j,
        &modifiers,
        &CommodityStyles::new(),
        today,
        verbose_tags,
        j.txns.clone(),
    )?;
    let mut opts = opts.clone();
    opts.spec.query = Query::Any;
    if raw.bool("diff") {
        diff_output(layout_from_raw_opts(&opts)?, &j, &txns)
    } else {
        print(&opts, Journal { txns, ..j })
    }
}

/// The auto posting rule of the query arguments and the --add-posting
/// options (transactionModifierFromOpts).
fn transaction_modifier_from_opts(opts: &CliOpts) -> Result<TransactionModifier, String> {
    let query = opts
        .raw
        .args()
        .map(quote_arg_if_needed)
        .collect::<Vec<_>>()
        .join(" ");
    let rules = opts
        .raw
        .list("add-posting")
        .map(|s| parse_tm_posting_rule(&opts.input, s))
        .collect::<Result<_, _>>()?;
    Ok(TransactionModifier {
        query,
        rules,
        pos: SourcePos::null(),
    })
}

/// An argument in double quotes, its double quotes backslash-escaped, if
/// it contains a quote, white space or `<`/`>` (Hledger.Utils.String's
/// quoteIfNeeded).
fn quote_arg_if_needed(s: &str) -> String {
    if s.contains(['\'', '"', ' ', '\t', '\n', '\r', '<', '>']) {
        format!("\"{}\"", s.replace('"', "\\\""))
    } else {
        s.to_string()
    }
}

/// A replacement of a source file's lines `[start, end)`, numbered from 1,
/// with new lines (Edit).
type Edit = (usize, usize, Vec<String>);

/// How many lines of unchanged context surround each change, as with
/// diff -U3 (diffContextLines).
const DIFF_CONTEXT_LINES: usize = 3;

/// The changed transactions as a unified diff of the files they were read
/// from, for patch. Those with no journal entry of their own to replace
/// (generated by a periodic transaction rule, or read from CSV or timeclock
/// data) are left out, and counted on stderr (diffOutput).
fn diff_output(layout: PostingLayout, j: &Journal, new: &[Transaction]) -> Result<String, String> {
    let mut edits: BTreeMap<&str, Vec<Edit>> = BTreeMap::new();
    let mut unpatchable: BTreeMap<String, usize> = BTreeMap::new();
    for (t, t2) in j.txns.iter().zip(new).filter(|(t, t2)| t != t2) {
        let (start, end) = &t.pos;
        if t.has_tag(GENERATED_TRANSACTION_TAG) {
            // its position is the rule's, which must not be overwritten
            *unpatchable
                .entry("generated by a periodic transaction rule".to_string())
                .or_default() += 1;
        } else if end.line > start.line {
            let t2 = transaction_with_mostly_original_postings(false, t2.clone());
            let shown = show_transaction(&t2, layout, false);
            let mut lines: Vec<String> = text_lines(&shown).into_iter().map(String::from).collect();
            while lines.last().is_some_and(|l| l.is_empty()) {
                lines.pop();
            }
            edits
                .entry(&start.file)
                .or_default()
                .push((start.line, end.line, lines));
        } else {
            *unpatchable
                .entry(format!("read from {}", start.file))
                .or_default() += 1;
        }
    }
    let n: usize = unpatchable.values().sum();
    if n > 0 {
        let mut warning = format!(
            "warning: {n} changed transaction{} not shown in the diff, having no journal entry to patch:\n",
            if n == 1 { " is" } else { "s are" }
        );
        for (reason, count) in &unpatchable {
            warning.push_str(&format!("  {count} {reason}\n"));
        }
        eprint!("{warning}");
    }
    let mut out = String::new();
    for (file, mut es) in edits {
        let Some((_, text)) = j.files.iter().find(|(f, _)| f == file) else {
            continue;
        };
        es.sort_by_key(|e| e.0);
        let old = text_lines(text);
        let new = apply_edits(&es, &old);
        let new: Vec<&str> = new.iter().map(String::as_str).collect();
        out.push_str(&unified_diff(file, &old, &new));
    }
    Ok(out)
}

/// The lines of a text, without their newlines; a final newline ends the
/// last line rather than starting another (Data.Text's lines).
fn text_lines(s: &str) -> Vec<&str> {
    let mut lines: Vec<&str> = s.split('\n').collect();
    if lines.last() == Some(&"") {
        lines.pop();
    }
    lines
}

/// Lines with some line ranges, `[start, end)` numbered from 1, replaced;
/// edits sorted by start line, any overlapping an earlier one skipped
/// (applyEdits).
fn apply_edits(edits: &[Edit], lines: &[&str]) -> Vec<String> {
    let mut out = Vec::new();
    let (mut lineno, mut rest) = (1, lines);
    for (start, end, new) in edits {
        if *start < lineno || end < start {
            continue;
        }
        let (before, after) = rest.split_at((start - lineno).min(rest.len()));
        out.extend(before.iter().map(|s| s.to_string()));
        out.extend(new.iter().cloned());
        rest = &after[(end - start).min(after.len())..];
        lineno = *end;
    }
    out.extend(rest.iter().map(|s| s.to_string()));
    out
}

/// The differences between two versions of a file's lines as a unified
/// diff with three lines of context, or nothing if they are the same
/// (unifiedDiff, with the Diff package's getContextDiff and
/// prettyContextDiff).
fn unified_diff(file: &str, old: &[&str], new: &[&str]) -> String {
    let hunks = context_hunks(grouped_diff(old, new), DIFF_CONTEXT_LINES);
    if hunks.is_empty() {
        return String::new();
    }
    let mut out = format!("--- {file}\n+++ {file}\n");
    for hunk in &hunks {
        let numbers = |first: bool| -> Vec<usize> {
            hunk.iter()
                .flat_map(|run| match (run, first) {
                    (Run::Both(ls, _) | Run::First(ls), true)
                    | (Run::Both(_, ls) | Run::Second(ls), false) => ls.as_slice(),
                    _ => &[],
                })
                .map(|l| l.0)
                .collect()
        };
        let range = |ns: Vec<usize>| match ns.as_slice() {
            [] => "0,0".to_string(),
            [n] => n.to_string(),
            [n, ..] => format!("{n},{}", ns.len()),
        };
        out.push_str(&format!(
            "@@ -{} +{} @@\n",
            range(numbers(true)),
            range(numbers(false))
        ));
        for run in hunk {
            let (mark, lines) = match run {
                Run::Both(ls, _) => (' ', ls),
                Run::First(ls) => ('-', ls),
                Run::Second(ls) => ('+', ls),
            };
            for (_, l) in lines {
                out.push(mark);
                out.push_str(l);
                out.push('\n');
            }
        }
    }
    out
}

/// A line and its number from 1.
type Line<'a> = (usize, &'a str);

/// A run of lines: in the first text only, the second only, or both
/// (PolyDiff of lists).
enum Run<'a> {
    First(Vec<Line<'a>>),
    Second(Vec<Line<'a>>),
    Both(Vec<Line<'a>>, Vec<Line<'a>>),
}

/// The diff of two texts' lines as runs of each kind (getGroupedDiff).
fn grouped_diff<'a>(a: &[&'a str], b: &[&'a str]) -> Vec<Run<'a>> {
    let mut runs: Vec<Run> = Vec::new();
    let (mut i, mut j) = (0, 0);
    for step in edit_script(a, b) {
        match step {
            Step::F => {
                let l = (i + 1, a[i]);
                i += 1;
                match runs.last_mut() {
                    Some(Run::First(ls)) => ls.push(l),
                    _ => runs.push(Run::First(vec![l])),
                }
            }
            Step::S => {
                let l = (j + 1, b[j]);
                j += 1;
                match runs.last_mut() {
                    Some(Run::Second(ls)) => ls.push(l),
                    _ => runs.push(Run::Second(vec![l])),
                }
            }
            Step::B => {
                let (x, y) = ((i + 1, a[i]), (j + 1, b[j]));
                (i, j) = (i + 1, j + 1);
                match runs.last_mut() {
                    Some(Run::Both(xs, ys)) => {
                        xs.push(x);
                        ys.push(y);
                    }
                    _ => runs.push(Run::Both(vec![x], vec![y])),
                }
            }
        }
    }
    runs
}

/// The changes with `n` lines of common context around each, as hunks:
/// common runs shortened to the context they give the changes before and
/// after them, or split where they are longer than both contexts
/// (getContextDiffNumbered's doPrefix and doSuffix, then groupBy').
fn context_hunks<'a>(runs: Vec<Run<'a>>, n: usize) -> Vec<Vec<Run<'a>>> {
    let mut kept: Vec<Run> = Vec::new();
    let mut runs: VecDeque<Run> = runs.into();
    let mut before_change = true;
    while let Some(run) = runs.pop_front() {
        let last = runs.is_empty();
        match (before_change, run) {
            (true, Run::Both(xs, ys)) => {
                if last {
                    break;
                }
                let keep_end = |mut ls: Vec<Line<'a>>| {
                    ls.drain(..ls.len().saturating_sub(n));
                    ls
                };
                kept.push(Run::Both(keep_end(xs), keep_end(ys)));
                before_change = false;
            }
            (true, run) => {
                runs.push_front(run);
                before_change = false;
            }
            (false, Run::Both(mut xs, mut ys)) => {
                if last {
                    xs.truncate(n);
                    ys.truncate(n);
                    kept.push(Run::Both(xs, ys));
                } else if xs.len() <= 2 * n {
                    kept.push(Run::Both(xs, ys));
                    before_change = true;
                } else {
                    let (xs2, ys2) = (xs.split_off(n), ys.split_off(n));
                    kept.push(Run::Both(xs, ys));
                    runs.push_front(Run::Both(xs2, ys2));
                    before_change = true;
                }
            }
            (false, run) => kept.push(run),
        }
    }
    let mut hunks: Vec<Vec<Run>> = Vec::new();
    for run in kept {
        match hunks.last_mut() {
            Some(h) if !matches!((h.last(), &run), (Some(Run::Both(..)), Run::Both(..))) => {
                h.push(run)
            }
            _ => hunks.push(vec![run]),
        }
    }
    hunks
}

/// One step of an edit script (DI): a line of the first text only, of the
/// second only, or of both.
#[derive(Clone, Copy)]
enum Step {
    F,
    S,
    B,
}

/// An edit script so far, latest step first, sharing its earlier steps
/// with other scripts.
struct Path {
    step: Step,
    prev: Option<Rc<Path>>,
}

impl Drop for Path {
    /// Drops a long unshared chain without recursing.
    fn drop(&mut self) {
        let mut prev = self.prev.take();
        while let Some(p) = prev {
            prev = Rc::try_unwrap(p).ok().and_then(|mut p| p.prev.take());
        }
    }
}

/// How far a script reaches into the two texts (DL).
struct Reach {
    i: usize,
    j: usize,
    path: Option<Rc<Path>>,
}

/// The shortest edit script turning `a` into `b`, by the O(ND) algorithm
/// exactly as the Diff package runs it (lcs, dstep, addsnake), so that the
/// same script is chosen among equally short ones: on each diagonal the
/// script reaching furthest into `a` is kept, the one that came by an
/// insertion if they reach equally far.
fn edit_script(a: &[&str], b: &[&str]) -> Vec<Step> {
    // follow common lines (addsnake)
    let snake = |mut r: Reach| {
        while r.i < a.len() && r.j < b.len() && a[r.i] == b[r.j] {
            r.path = Some(Rc::new(Path {
                step: Step::B,
                prev: r.path.take(),
            }));
            (r.i, r.j) = (r.i + 1, r.j + 1);
        }
        r
    };
    let extend = |r: &Reach, step: Step, i: usize, j: usize| {
        snake(Reach {
            i,
            j,
            path: Some(Rc::new(Path {
                step,
                prev: r.path.clone(),
            })),
        })
    };
    let mut reaches = vec![snake(Reach {
        i: 0,
        j: 0,
        path: None,
    })];
    loop {
        if let Some(r) = reaches.iter().find(|r| r.i == a.len() && r.j == b.len()) {
            let mut steps = Vec::new();
            let mut node = r.path.as_deref();
            while let Some(p) = node {
                steps.push(p.step);
                node = p.prev.as_deref();
            }
            steps.reverse();
            return steps;
        }
        let mut next = reaches.iter().flat_map(|r| {
            [
                extend(r, Step::F, r.i + 1, r.j),
                extend(r, Step::S, r.i, r.j + 1),
            ]
        });
        let mut merged = Vec::with_capacity(reaches.len() + 1);
        merged.extend(next.next());
        while let Some(x) = next.next() {
            merged.push(match next.next() {
                // max x y, with x <= y when x reaches less far into a
                Some(y) if (x.i == y.i && x.j > y.j) || x.i < y.i => y,
                _ => x,
            });
        }
        reaches = merged;
    }
}
