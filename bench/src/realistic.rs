//! A household journal for timing the daily reports (balance, register, is,
//! bs, roi): declared and typed accounts, a salary, everyday spending on a
//! card, bills, savings, a brokerage account buying and selling lotful
//! stocks at cost (gains inferred), dividends, some spending in euros, and
//! market prices. One year per 10,000 transactions (at least one), ending
//! 2025-12-31; the same text for the same size.

use std::fmt::Write;

use crate::generate::{days_from_civil, show_day};

const TICKERS: [&str; 3] = ["ABC", "DEF", "GHI"];

/// (account, weight in percent, lowest and highest amount in cents) of the
/// everyday expenses, paid by card, from checking, or in cash.
const SPENDING: &[(&str, u64, i64, i64)] = &[
    ("expenses:food:groceries", 22, 1500, 18000),
    ("expenses:food:restaurants", 14, 1200, 9000),
    ("expenses:transport:fuel", 8, 3000, 8000),
    ("expenses:transport:transit", 8, 275, 2500),
    ("expenses:shopping", 10, 500, 25000),
    ("expenses:entertainment", 6, 800, 6000),
    ("expenses:health", 4, 2000, 30000),
    ("expenses:fees", 2, 100, 3500),
];

const HEADER: &str = "\
; A household journal generated by hledgers-bench.

commodity $1,000.00
commodity 1,000.00 €
commodity 0.000 ABC  ; lots:
commodity 0.000 DEF  ; lots:
commodity 0.000 GHI  ; lots:

account assets                        ; type: A
account assets:bank:checking          ; type: C
account assets:bank:savings           ; type: C
account assets:cash                   ; type: C
account assets:investments:brokerage
account liabilities                   ; type: L
account liabilities:credit card
account equity                        ; type: E
account equity:opening balances
account income                        ; type: R
account income:salary
account income:interest
account income:investments:dividends
account income:investments:gains      ; type: G
account expenses                      ; type: X
account expenses:food:groceries
account expenses:food:restaurants
account expenses:housing:rent
account expenses:housing:utilities
account expenses:transport:fuel
account expenses:transport:transit
account expenses:shopping
account expenses:entertainment
account expenses:health
account expenses:fees
account expenses:travel

";

/// The journal with `txns` transactions.
pub fn journal(txns: usize) -> String {
    let years = txns.div_ceil(10_000).max(1) as i64;
    let start = days_from_civil(2026 - years, 1, 1);
    let days = days_from_civil(2026, 1, 1) - start;
    let date = |i: usize| start + (i as i64 * days).div_euclid(txns.max(1) as i64);
    let mut rng = Rng(0x2545_f491_4f6c_dd1d);
    let mut out = String::with_capacity(HEADER.len() + txns * 150);
    out.push_str(HEADER);
    // Prices in cents: a random walk per ticker, and euros in dollars per 100 €.
    let mut prices = [5000i64, 12000, 2500];
    let mut euro = 108i64;
    let mut held = [0i64; 3]; // thousandths of a share
    let mut next_price_day = start;
    for i in 0..txns {
        let day = date(i);
        // Weekly market prices up to this date, after the opening balances.
        while next_price_day <= day && i > 0 {
            for (t, p) in TICKERS.iter().zip(prices.iter_mut()) {
                *p = (*p + *p * rng.range(-40, 45) / 1000).max(100);
                let _ = writeln!(out, "P {} {t} {}", show_day(next_price_day), dollars(*p));
            }
            if (next_price_day - start) % 28 == 0 {
                euro = (euro + rng.range(-2, 2)).clamp(95, 125);
                let _ = writeln!(
                    out,
                    "P {} € ${}.{:02}",
                    show_day(next_price_day),
                    euro / 100,
                    euro % 100
                );
            }
            out.push('\n');
            next_price_day += 7;
        }
        let d = show_day(day);
        if i == 0 {
            let _ = write!(
                out,
                "{d} opening balances\n    assets:bank:checking   $4,000.00\n    assets:bank:savings   $12,500.00\n    \
                 liabilities:credit card   $-850.00\n    equity:opening balances\n\n"
            );
            continue;
        }
        // The first purchase comes early, so that roi has an investment to report on.
        let roll = if i == 1 { 105 } else { rng.range(0, 999) };
        match roll {
            0..=29 => {
                let pay = rng.range(310_000, 330_000);
                let _ = write!(
                    out,
                    "{d} * Employer | salary\n    assets:bank:checking   {}\n    income:salary\n\n",
                    dollars(pay)
                );
            }
            30..=44 => {
                let (account, amount, payee) = if roll < 40 {
                    ("expenses:housing:rent", 145_000, "Landlord")
                } else {
                    (
                        "expenses:housing:utilities",
                        rng.range(6_000, 22_000),
                        "Power company",
                    )
                };
                let _ = write!(
                    out,
                    "{d} * {payee}\n    {account}   {}\n    assets:bank:checking\n\n",
                    dollars(amount)
                );
            }
            45..=79 => {
                let amount = rng.range(20_000, 120_000);
                let _ = write!(
                    out,
                    "{d} * card payment\n    liabilities:credit card   {}\n    assets:bank:checking\n\n",
                    dollars(amount)
                );
            }
            80..=99 => {
                let (to, what, amount) = if roll < 92 {
                    ("assets:bank:savings", "savings", rng.range(10_000, 60_000))
                } else {
                    ("assets:cash", "cash withdrawal", 2_000 * rng.range(1, 10))
                };
                let _ = write!(
                    out,
                    "{d} {what}\n    {to}   {}\n    assets:bank:checking\n\n",
                    dollars(amount)
                );
            }
            100..=104 => {
                let interest = rng.range(100, 4_000);
                let _ = write!(
                    out,
                    "{d} * Bank | interest\n    assets:bank:savings   {}\n    income:interest\n\n",
                    dollars(interest)
                );
            }
            105..=139 => {
                let t = rng.range(0, 2) as usize;
                let shares = rng.range(1_000, 25_000);
                let unit = prices[t] + rng.range(-prices[t] / 50, prices[t] / 50);
                let _ = write!(
                    out,
                    "{d} * Broker | buy {}\n    assets:investments:brokerage   {} {} @ {}\n    \
                     assets:bank:checking   {}\n\n",
                    TICKERS[t],
                    thousandths(shares),
                    TICKERS[t],
                    dollars(unit),
                    dollars(-(shares * unit + 500) / 1000)
                );
                held[t] += shares;
            }
            140..=154 if held.iter().any(|&h| h > 0) => {
                let t = (0..3)
                    .map(|k| (k + roll as usize) % 3)
                    .find(|&t| held[t] > 0)
                    .unwrap();
                let shares = (held[t] * rng.range(10, 60) / 100).max(1).min(held[t]);
                let unit = prices[t] + rng.range(-prices[t] / 50, prices[t] / 50);
                let _ = write!(
                    out,
                    "{d} * Broker | sell {}\n    assets:investments:brokerage   {} {} @ {}\n    \
                     assets:bank:checking   {}\n\n",
                    TICKERS[t],
                    thousandths(-shares),
                    TICKERS[t],
                    dollars(unit),
                    dollars((shares * unit + 500) / 1000)
                );
                held[t] -= shares;
            }
            155..=169 => {
                let t = rng.range(0, 2) as usize;
                let amount = rng.range(500, 9_000);
                let _ = write!(
                    out,
                    "{d} * Broker | dividend {}\n    assets:investments:brokerage   {}\n    \
                     income:investments:dividends\n\n",
                    TICKERS[t],
                    dollars(amount)
                );
            }
            170..=184 => {
                let cents = rng.range(1_500, 40_000);
                let paid = cents * euro / 100;
                let _ = write!(
                    out,
                    "{d} Café Europa\n    expenses:travel   {}.{:02} € @@ {}\n    liabilities:credit card\n\n",
                    cents / 100,
                    cents % 100,
                    dollars(paid)
                );
            }
            _ => {
                let total: u64 = SPENDING.iter().map(|s| s.1).sum();
                let mut pick = rng.range(0, total as i64 - 1) as u64;
                let &(account, _, lo, hi) = SPENDING
                    .iter()
                    .find(|s| {
                        let hit = pick < s.1;
                        pick = pick.saturating_sub(s.1);
                        hit
                    })
                    .unwrap();
                let amount = rng.range(lo, hi);
                let (from, status) = match rng.range(0, 9) {
                    0..=6 => ("liabilities:credit card", "* "),
                    7 | 8 => ("assets:bank:checking", ""),
                    _ => ("assets:cash", ""),
                };
                let payee = account.rsplit(':').next().unwrap();
                let shop = rng.range(1, 6);
                let _ = write!(
                    out,
                    "{d} {status}{payee} {shop}\n    {account}   {}\n    {from}\n\n",
                    dollars(amount)
                );
            }
        }
    }
    out
}

/// `$1,234.56` from cents, the sign before the symbol's amount: `$-1,234.56`.
fn dollars(cents: i64) -> String {
    let sign = if cents < 0 { "-" } else { "" };
    let c = cents.unsigned_abs();
    format!("${sign}{}.{:02}", grouped(c / 100), c % 100)
}

fn thousandths(n: i64) -> String {
    let sign = if n < 0 { "-" } else { "" };
    let n = n.unsigned_abs();
    format!("{sign}{}.{:03}", n / 1000, n % 1000)
}

fn grouped(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (k, c) in digits.chars().enumerate() {
        if k > 0 && (digits.len() - k).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// splitmix64.
struct Rng(u64);

impl Rng {
    /// A number from lo to hi inclusive.
    fn range(&mut self, lo: i64, hi: i64) -> i64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^= z >> 31;
        lo + (z % (hi - lo + 1) as u64) as i64
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sizes_and_first_purchase() {
        assert_eq!(journal(0), HEADER);
        let j = journal(100);
        let txns: Vec<&str> = j.lines().filter(|l| l.starts_with("20")).collect();
        assert_eq!(txns.len(), 100);
        assert_eq!(txns[0], "2025-01-01 opening balances");
        assert!(txns[1].contains(" * Broker | buy "), "{}", txns[1]);
        assert!(j.contains("\nP 2025-01-01 ABC $"));
        assert_eq!(
            journal(100_000)
                .lines()
                .filter(|l| l.starts_with("20"))
                .count(),
            100_000
        );
    }
}
